def norm(lang: str) -> str:
    v = (lang or "").strip().lower()[:2]
    return v if v in LANGS else "en"


def say(key: str, lang: str, **values: object) -> str:
    """One frame in one language. A missing value renders empty rather than raising."""
    frame = FRAMES[key][norm(lang)]
    out = re.sub(r"\{(\w+)\}", lambda m: str(values.get(m.group(1), "")).strip(), frame)
    out = re.sub(r"\s+", " ", out)
    return re.sub(r"([.\u0964])(?:\s*[.\u0964])+", r"\1", out).strip()


def join(items: list[str], lang: str) -> str:
    items = [i for i in items if i]
    if len(items) < 2:
        return "".join(items)
    return ", ".join(items[:-1]) + _JOIN[norm(lang)] + items[-1]


_SHORT = re.compile(r"\s*\((?!pregnancy).*?\)|\s+w/.*$")


def short_test(name: str) -> str:
    """'Coagulation (PT/PTT/INR)' -> 'Coagulation', for speaking."""
    return _SHORT.sub("", name or "").strip() or (name or "")


def speakable(text: str, limit: int = 130) -> str:
    """A stored report reduced to what a person would read out: the finding, no reference ranges."""
    t = text or ""
    m = re.search(r"^Interpretation:\s*(.+)$", t, re.M | re.I)
    if m:
        t = m.group(1)
    elif "\n" in t:
        t = " ".join(t.splitlines()[1:]) or t
    t = re.sub(r"\([^)]*\)", "", t)
    t = re.sub(r"\s+", " ", t).strip()
    # Whole sentences only, as many as fit.
    out = ""
    for s in re.split(r"(?<=[.;])\s+", t):
        if out and len(out) + len(s) + 1 > limit:
            break
        out = f"{out} {s}".strip()
    if len(out) > limit:
        cut = out[:limit]
        out = cut[: cut.rfind(",")] if "," in cut[40:] else cut.rsplit(" ", 1)[0]
    out = re.sub(r"\s+([,.;])", r"\1", out).rstrip(" .;,")
    # One spoken sentence: the frame around it is the other.
    return re.sub(r"[.;]\s+", ", ", out)
